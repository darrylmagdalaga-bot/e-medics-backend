import { useState, useRef } from 'react';
import { API_URL } from '../api-config';
import {
  BarChart3, FileText, ShieldAlert, ShieldCheck, X, CheckCircle2,
  Calendar, Printer, Download, FileSpreadsheet, AlertCircle, ClipboardList
} from 'lucide-react';
import { toast } from 'sonner';

// ─────────────────────────────────────────────────────────────────────────────
// PHARMACY-ONLY Inventory Log Data — completely isolated from Warehouse
// ─────────────────────────────────────────────────────────────────────────────
interface PharmacyLogEntry {
  measure: string;
  description: string;
  received: number;
  inventory: number;
  issued: number;
  price: number;
}

// Pharmacy-only sample data (this would come from Pharmacy stock records)


const MONTHS = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December'
];

// ─────────────────────────────────────────────────────────────────────────────
interface ReportsScreenProps {
  role?: string;
}

export function ReportsScreen({ role = 'pharmacy' }: ReportsScreenProps) {
  const isPharmacyRole = role === 'pharmacy' || role === 'admin';

  const [showMonthPicker, setShowMonthPicker] = useState(false);
  const [selectedMonth, setSelectedMonth] = useState('');
  const [selectedYear, setSelectedYear] = useState(new Date().getFullYear().toString());
  const [monthError, setMonthError] = useState('');

  const [reportGenerated, setReportGenerated] = useState(false);
  const [reportData, setReportData] = useState<PharmacyLogEntry[]>([]);
  const [reportPeriodLabel, setReportPeriodLabel] = useState('');

  const printRef = useRef<HTMLDivElement>(null);



  // ── Generate Report ──────────────────────────────────────────────────────
  const handleGenerateReport = async () => {
    if (!selectedMonth) {
      setMonthError('Please select a month to generate report.');
      toast.error('Please select a month to generate report.');
      return;
    }
    setMonthError('');
    
    const toastId = toast.loading('Generating report...');
    
    try {
      const monthIdx = MONTHS.indexOf(selectedMonth) + 1;
      const res = await fetch(`${API_URL}/api/pharmacy/reports/inventory-log?month=${monthIdx}&year=${selectedYear}`, {
        headers: { 'Bypass-Tunnel-Reminder': 'true' }
      });
      const data = await res.json();
      
      setReportData(data);
      setReportPeriodLabel(`${selectedMonth} ${selectedYear}`);
      setReportGenerated(true);
      setShowMonthPicker(false);
      
      toast.success('Pharmacy Inventory Log generated successfully.', {
        id: toastId,
        description: `${selectedMonth} ${selectedYear} · ${data.length} items`,
      });
    } catch (err) {
      console.error(err);
      toast.error('Failed to generate report', { id: toastId });
    }
  };

  // ── Print handler ────────────────────────────────────────────────────────
  const handlePrint = () => {
    const content = printRef.current;
    if (!content) return;
    const printWindow = window.open('', '_blank');
    if (!printWindow) return;

    printWindow.document.write(`
      <html><head><title>Pharmacy Inventory Log — ${reportPeriodLabel}</title>
      <style>
        body { font-family: 'Segoe UI', Arial, sans-serif; padding: 40px; color: #1a1a5e; }
        h1 { text-align: center; font-size: 20px; margin-bottom: 4px; }
        h2 { text-align: center; font-size: 14px; color: #666; font-weight: 500; margin-bottom: 20px; }
        table { width: 100%; border-collapse: collapse; font-size: 11px; }
        th { background: #f0f0f5; padding: 10px 8px; text-align: left; font-weight: 700; text-transform: uppercase; letter-spacing: 0.5px; border-bottom: 2px solid #ddd; }
        td { padding: 8px; border-bottom: 1px solid #eee; }
        tr:nth-child(even) { background: #fafafa; }
        .text-right { text-align: right; }
        .text-center { text-align: center; }
        .total-row { font-weight: 800; background: #f0f0f5 !important; border-top: 2px solid #999; }
        .footer { text-align: center; margin-top: 30px; font-size: 10px; color: #999; }
      </style>
      </head><body>
        <h1>PHARMACY INVENTORY LOG SHEET</h1>
        <h2>Catbalogan City Health Department · ${reportPeriodLabel}</h2>
        ${content.querySelector('table')?.outerHTML || ''}
        <p class="footer">Generated by e-MEDICS System · Pharmacy Module · Catbalogan City Health Dept.</p>
      </body></html>
    `);
    printWindow.document.close();
    printWindow.print();
  };

  // ── CSV Export handler ───────────────────────────────────────────────────
  const handleExportCSV = () => {
    if (reportData.length === 0) return;
    const headers = ['SN', 'MEASURE', 'DESCRIPTION', 'RECEIVED', 'INVENTORY', 'TOTAL STOCK', 'ISSUED', 'PRICE', 'TOTAL'];
    const rows = reportData.map((item, i) => {
      const totalStock = item.inventory + item.received;
      const total = item.issued * item.price;
      return [i + 1, item.measure, `"${item.description}"`, item.received, item.inventory, totalStock, item.issued, item.price.toFixed(2), total.toFixed(2)].join(',');
    });

    // Grand totals row
    const grandReceived = reportData.reduce((s, r) => s + r.received, 0);
    const grandInventory = reportData.reduce((s, r) => s + r.inventory, 0);
    const grandTotalStock = reportData.reduce((s, r) => s + r.inventory + r.received, 0);
    const grandIssued = reportData.reduce((s, r) => s + r.issued, 0);
    const grandTotal = reportData.reduce((s, r) => s + r.issued * r.price, 0);
    rows.push(['', '', 'GRAND TOTAL', grandReceived, grandInventory, grandTotalStock, grandIssued, '', grandTotal.toFixed(2)].join(','));

    const csv = [headers.join(','), ...rows].join('\n');
    const blob = new Blob([csv], { type: 'text/csv' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Pharmacy_Inventory_Log_${reportPeriodLabel.replace(' ', '_')}.csv`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success('Report exported as CSV successfully.');
  };

  // ── Computed totals ──────────────────────────────────────────────────────
  const grandReceived = reportData.reduce((s, r) => s + r.received, 0);
  const grandInventory = reportData.reduce((s, r) => s + r.inventory, 0);
  const grandTotalStock = reportData.reduce((s, r) => s + r.inventory + r.received, 0);
  const grandIssued = reportData.reduce((s, r) => s + r.issued, 0);
  const grandTotal = reportData.reduce((s, r) => s + r.issued * r.price, 0);

  // ─────────────────────────────────────────────────────────────────────────
  return (
    <div className="max-w-7xl mx-auto p-4 lg:p-8 space-y-6 min-h-full font-sans">

      {/* ── Header ── */}
      <div className="flex items-start justify-between gap-4">
        <div>
          <h1 className="text-2xl sm:text-3xl font-black text-foreground tracking-tight">Reports</h1>
          <p className="text-sm text-muted-foreground mt-0.5">
            Generate official logs and summaries ·{' '}
            {isPharmacyRole
              ? <span className="text-primary font-bold">Pharmacy Module</span>
              : <span className="text-red-500 font-bold">Access Restricted — Inventory Role</span>}
          </p>
        </div>
      </div>

      {/* ── Role Notice ── */}
      {!isPharmacyRole ? (
        <div className="bg-red-50 border border-red-100 p-4 rounded-2xl flex items-start gap-4">
          <div className="w-10 h-10 bg-white rounded-xl flex items-center justify-center shrink-0 shadow-sm border border-red-100">
            <ShieldAlert className="w-6 h-6 text-red-500" />
          </div>
          <div>
            <p className="text-sm font-black text-red-800 uppercase tracking-wider">Access Restricted</p>
            <p className="text-xs text-red-700 mt-0.5">
              Reports in this section are exclusively for <strong>Pharmacy users</strong>. Inventory/Warehouse users do not have access to Pharmacy reports.
            </p>
          </div>
        </div>
      ) : (
        <div className="bg-primary/5 border border-primary/10 p-4 rounded-2xl flex items-start gap-4">
          <div className="w-10 h-10 bg-white rounded-xl flex items-center justify-center shrink-0 shadow-sm border border-primary/10">
            <ShieldCheck className="w-6 h-6 text-primary" />
          </div>
          <div>
            <p className="text-sm font-black text-primary/80 uppercase tracking-wider">Pharmacy Reports</p>
            <p className="text-xs text-primary/70 mt-0.5">
              All reports use Pharmacy data exclusively. Inventory/Warehouse data is never included.
            </p>
          </div>
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* AVAILABLE REPORTS                                                 */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      <div>
        <h2 className="text-lg font-black text-foreground mb-4">Available Reports</h2>
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-5">

          {/* Pharmacy Inventory Log Card */}
          <button
            onClick={() => {
              if (!isPharmacyRole) {
                toast.error('This report is for Pharmacy use only.', { description: 'Access Denied' });
                return;
              }
              setShowMonthPicker(true);
            }}
            className={`text-left p-6 rounded-[16px] border transition-all group ${
              isPharmacyRole
                ? 'bg-white border-border/50 shadow-sm hover:shadow-xl hover:shadow-primary/5 hover:border-primary/20 cursor-pointer active:scale-[0.98]'
                : 'bg-gray-50 border-border/50 cursor-not-allowed opacity-60'
            }`}
          >
            <div className="flex items-center gap-4 mb-4">
              <div className={`w-12 h-12 rounded-2xl flex items-center justify-center transition-colors ${
                isPharmacyRole
                  ? 'bg-primary/10 text-primary group-hover:bg-primary group-hover:text-white'
                  : 'bg-gray-200 text-gray-400'
              }`}>
                <ClipboardList className="w-6 h-6" />
              </div>
              <div>
                <h3 className="text-sm font-black text-foreground">Pharmacy Inventory Log</h3>
                <p className="text-[10px] text-gray-400 font-medium mt-0.5">Monthly stock movement report</p>
              </div>
            </div>
            <p className="text-xs text-gray-500 leading-relaxed">
              Generates the official Pharmacy Inventory Log Sheet with received, beginning balance, total stock, issued, pricing, and computed totals.
            </p>
            <div className="mt-4 flex items-center gap-2">
              <span className={`text-[10px] font-black uppercase tracking-widest px-2.5 py-1 rounded-lg ${
                isPharmacyRole ? 'bg-primary/10 text-primary' : 'bg-gray-100 text-gray-400'
              }`}>
                {isPharmacyRole ? 'Available' : 'Restricted'}
              </span>
            </div>
          </button>

          {/* Placeholder: Future report cards */}
          <div className="p-6 rounded-[16px] border border-dashed border-border/50 bg-gray-50/50 flex flex-col items-center justify-center text-center min-h-[180px]">
            <FileText className="w-8 h-8 text-gray-300 mb-2" />
            <p className="text-xs font-bold text-gray-400">More reports coming soon</p>
            <p className="text-[10px] text-gray-300 mt-1">Dispensing Summary, Expiry Alerts, etc.</p>
          </div>
        </div>
      </div>

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* GENERATED REPORT TABLE                                            */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      {reportGenerated && (
        <div className="space-y-4">
          {/* Report header bar */}
          <div className="bg-white rounded-[16px] border border-border/50 shadow-sm p-6">
            <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
              <div className="flex items-center gap-4">
                <div className="p-2.5 bg-primary/10 rounded-xl">
                  <BarChart3 className="w-5 h-5 text-primary" />
                </div>
                <div>
                  <h3 className="text-lg font-black text-foreground">Pharmacy Inventory Log Sheet</h3>
                  <p className="text-xs text-gray-400 font-medium">
                    Catbalogan City Health Department · <span className="text-primary font-bold">{reportPeriodLabel}</span> · {reportData.length} items
                  </p>
                </div>
              </div>
              <div className="flex gap-2">
                <button
                  onClick={handlePrint}
                  className="px-4 py-2.5 bg-white border border-border/50 rounded-xl text-xs font-bold text-foreground hover:bg-gray-50 transition-all shadow-sm flex items-center gap-2 active:scale-95"
                >
                  <Printer className="w-4 h-4" /> Print
                </button>
                <button
                  onClick={handleExportCSV}
                  className="px-4 py-2.5 bg-white border border-border/50 rounded-xl text-xs font-bold text-foreground hover:bg-gray-50 transition-all shadow-sm flex items-center gap-2 active:scale-95"
                >
                  <FileSpreadsheet className="w-4 h-4" /> Export CSV
                </button>
                <button
                  onClick={() => {
                    setShowMonthPicker(true);
                  }}
                  className="px-4 py-2.5 bg-primary text-white rounded-xl text-xs font-bold hover:bg-primary/90 transition-all shadow-lg shadow-primary/20 flex items-center gap-2 active:scale-95"
                >
                  <Calendar className="w-4 h-4" /> Change Period
                </button>
              </div>
            </div>
          </div>

          {/* Report table */}
          <div ref={printRef} className="bg-white rounded-[16px] border border-border/50 shadow-sm overflow-hidden">
            <div className="overflow-x-auto">
              <table className="w-full">
                <thead className="bg-muted/40 border-b border-border/50">
                  <tr>
                    <th className="px-4 py-4 text-center text-[10px] font-black text-gray-500 uppercase tracking-widest w-14">SN</th>
                    <th className="px-4 py-4 text-left text-[10px] font-black text-gray-500 uppercase tracking-widest">Measure</th>
                    <th className="px-4 py-4 text-left text-[10px] font-black text-gray-500 uppercase tracking-widest">Description</th>
                    <th className="px-4 py-4 text-right text-[10px] font-black text-gray-500 uppercase tracking-widest">Received</th>
                    <th className="px-4 py-4 text-right text-[10px] font-black text-gray-500 uppercase tracking-widest">Inventory</th>
                    <th className="px-4 py-4 text-right text-[10px] font-black text-gray-500 uppercase tracking-widest">Total Stock</th>
                    <th className="px-4 py-4 text-right text-[10px] font-black text-gray-500 uppercase tracking-widest">Issued</th>
                    <th className="px-4 py-4 text-right text-[10px] font-black text-gray-500 uppercase tracking-widest">Price</th>
                    <th className="px-4 py-4 text-right text-[10px] font-black text-gray-500 uppercase tracking-widest">Total</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-50">
                  {reportData.length === 0 ? (
                    <tr>
                      <td colSpan={9} className="px-8 py-16 text-center text-gray-400 font-medium">
                        <AlertCircle className="w-8 h-8 mx-auto mb-3 text-gray-300" />
                        No pharmacy data found for <strong>{reportPeriodLabel}</strong>.
                      </td>
                    </tr>
                  ) : (
                    <>
                      {reportData.map((item, idx) => {
                        const totalStock = item.inventory + item.received;
                        const total = item.issued * item.price;
                        return (
                          <tr key={idx} className="hover:bg-gray-50/50 transition-colors">
                            <td className="px-4 py-4 text-center text-xs font-bold text-gray-400">{idx + 1}</td>
                            <td className="px-4 py-4 text-xs font-bold text-gray-600">{item.measure}</td>
                            <td className="px-4 py-4 text-sm font-bold text-foreground">{item.description}</td>
                            <td className="px-4 py-4 text-sm font-bold text-green-600 text-right">{item.received.toLocaleString()}</td>
                            <td className="px-4 py-4 text-sm font-bold text-blue-600 text-right">{item.inventory.toLocaleString()}</td>
                            <td className="px-4 py-4 text-sm font-black text-foreground text-right">{totalStock.toLocaleString()}</td>
                            <td className="px-4 py-4 text-sm font-bold text-orange-600 text-right">{item.issued.toLocaleString()}</td>
                            <td className="px-4 py-4 text-sm font-bold text-gray-600 text-right">₱{item.price.toFixed(2)}</td>
                            <td className="px-4 py-4 text-sm font-black text-primary text-right">₱{total.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}</td>
                          </tr>
                        );
                      })}
                      {/* GRAND TOTAL ROW */}
                      <tr className="bg-muted/40 border-t-2 border-gray-300 total-row">
                        <td colSpan={3} className="px-4 py-4 text-sm font-black text-foreground text-right uppercase tracking-wider">Grand Total</td>
                        <td className="px-4 py-4 text-sm font-black text-green-700 text-right">{grandReceived.toLocaleString()}</td>
                        <td className="px-4 py-4 text-sm font-black text-blue-700 text-right">{grandInventory.toLocaleString()}</td>
                        <td className="px-4 py-4 text-sm font-black text-foreground text-right">{grandTotalStock.toLocaleString()}</td>
                        <td className="px-4 py-4 text-sm font-black text-orange-700 text-right">{grandIssued.toLocaleString()}</td>
                        <td className="px-4 py-4 text-sm font-black text-gray-500 text-right">—</td>
                        <td className="px-4 py-4 text-base font-black text-primary text-right">₱{grandTotal.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}</td>
                      </tr>
                    </>
                  )}
                </tbody>
              </table>
            </div>
          </div>

          {/* Summary cards */}
          {reportData.length > 0 && (
            <div className="grid grid-cols-2 md:grid-cols-5 gap-4">
              {[
                { label: 'Total Received', value: grandReceived.toLocaleString(), color: 'text-green-600', bg: 'bg-green-50' },
                { label: 'Beginning Inventory', value: grandInventory.toLocaleString(), color: 'text-blue-600', bg: 'bg-blue-50' },
                { label: 'Total Stock', value: grandTotalStock.toLocaleString(), color: 'text-foreground', bg: 'bg-gray-50' },
                { label: 'Total Issued', value: grandIssued.toLocaleString(), color: 'text-orange-600', bg: 'bg-orange-50' },
                { label: 'Grand Total Value', value: `₱${grandTotal.toLocaleString(undefined, { minimumFractionDigits: 2 })}`, color: 'text-primary', bg: 'bg-primary/5' },
              ].map((s, i) => (
                <div key={i} className={`${s.bg} p-4 rounded-2xl border border-border/50`}>
                  <p className="text-gray-400 text-[10px] font-black uppercase tracking-widest mb-1">{s.label}</p>
                  <p className={`text-xl font-black ${s.color}`}>{s.value}</p>
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* MONTH PICKER MODAL                                                */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      {showMonthPicker && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/40 backdrop-blur-sm animate-in fade-in duration-200">
          <div className="bg-white w-full max-w-md rounded-[16px] shadow-2xl border border-border/50 flex flex-col overflow-hidden">

            {/* Modal Header */}
            <div className="p-7 border-b border-gray-50">
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-3">
                  <div className="p-2.5 bg-primary/10 rounded-xl">
                    <Calendar className="w-5 h-5 text-primary" />
                  </div>
                  <div>
                    <h2 className="text-xl font-black text-foreground tracking-tight">Generate Report</h2>
                    <p className="text-xs text-gray-400 font-medium">Select reporting period</p>
                  </div>
                </div>
                <button
                  onClick={() => { setShowMonthPicker(false); setMonthError(''); }}
                  className="p-2 hover:bg-gray-100 rounded-xl transition-colors"
                >
                  <X className="w-5 h-5 text-gray-400" />
                </button>
              </div>
            </div>

            {/* Modal Body */}
            <div className="p-7 space-y-5">
              {/* Security note */}
              <div className="bg-primary/5 border border-primary/10 rounded-2xl p-3.5 flex items-center gap-3">
                <ShieldCheck className="w-5 h-5 text-primary shrink-0" />
                <p className="text-xs text-primary/80 font-medium leading-relaxed">
                  This report uses <strong>Pharmacy data only</strong>. Inventory/Warehouse data is excluded.
                </p>
              </div>

              {/* Month */}
              <div className="space-y-1.5">
                <label className="text-xs font-black text-gray-500 uppercase tracking-widest">
                  Month <span className="text-red-400">*</span>
                </label>
                <div className="relative">
                  <select
                    value={selectedMonth}
                    onChange={e => { setSelectedMonth(e.target.value); setMonthError(''); }}
                    className={`w-full px-4 py-3 bg-gray-50 border rounded-xl focus:outline-none focus:ring-2 focus:ring-primary/20 focus:bg-white transition-all text-sm font-medium appearance-none cursor-pointer ${monthError ? 'border-red-300 bg-red-50' : 'border-border/50'}`}
                  >
                    <option value="">Select month…</option>
                    {MONTHS.map(m => (
                      <option key={m} value={m}>{m}</option>
                    ))}
                  </select>
                  <svg className="absolute right-4 top-1/2 -translate-y-1/2 w-4 h-4 text-gray-400 pointer-events-none" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
                  </svg>
                </div>
                {monthError && <p className="text-xs text-red-500 font-bold">{monthError}</p>}
              </div>

              {/* Year (optional) */}
              <div className="space-y-1.5">
                <label className="text-xs font-black text-gray-500 uppercase tracking-widest">
                  Year <span className="text-gray-300 font-medium">(optional)</span>
                </label>
                <div className="relative">
                  <select
                    value={selectedYear}
                    onChange={e => setSelectedYear(e.target.value)}
                    className="w-full px-4 py-3 bg-gray-50 border border-border/50 rounded-xl focus:outline-none focus:ring-2 focus:ring-primary/20 focus:bg-white transition-all text-sm font-medium appearance-none cursor-pointer"
                  >
                    {[2024, 2025, 2026, 2027].map(y => (
                      <option key={y} value={y.toString()}>{y}</option>
                    ))}
                  </select>
                  <svg className="absolute right-4 top-1/2 -translate-y-1/2 w-4 h-4 text-gray-400 pointer-events-none" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
                  </svg>
                </div>
              </div>

              <p className="text-[10px] text-gray-400 font-medium">
                Fields marked with <span className="text-red-400 font-bold">*</span> are required.
              </p>
            </div>

            {/* Modal Footer */}
            <div className="p-7 border-t border-gray-50 bg-gray-50/50 flex items-center justify-end gap-3">
              <button
                onClick={() => { setShowMonthPicker(false); setMonthError(''); }}
                className="px-7 py-3 bg-white border border-border/50 text-sm font-black text-foreground rounded-xl hover:bg-gray-50 transition-all active:scale-95 shadow-sm"
              >
                Cancel
              </button>
              <button
                onClick={handleGenerateReport}
                className="px-10 py-3 bg-primary text-white text-sm font-black rounded-xl hover:bg-primary/90 transition-all active:scale-95 shadow-lg shadow-primary/20 flex items-center gap-2"
              >
                <CheckCircle2 className="w-4 h-4" /> Generate Report
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
